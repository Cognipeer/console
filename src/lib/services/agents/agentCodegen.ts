/**
 * Code export — turns an agent's config into a runnable `@cognipeer/agent-sdk`
 * project.
 *
 * Two rules shape everything here.
 *
 * **Inference goes back through the console.** The generated model is an
 * OpenAI-compatible client pointed at `<console>/api/client/v1`, not at the
 * provider. That is the whole governance story: an exported agent still spends
 * against the tenant's quota, still passes the gateway's guardrails, and still
 * shows up in tracing and Cost & Optimization. Pointing it at the raw provider
 * would produce a working agent that is invisible to every control the console
 * exists to provide.
 *
 * **Tools and MCP servers are not re-implemented.** They are reached through
 * `@cognipeer/console-sdk` against the same console. An exported project
 * therefore has no provider credentials in it at all — only a console API key —
 * and a tool whose upstream URL changes keeps working without regenerating.
 *
 * What this is NOT: a round-trip. Generated code is a starting point a team
 * edits; nothing re-imports it. `agentManifest.ts` is the round-trippable form.
 */

import type { IAgent, IAgentConfig, IAgentToolBinding } from '@/lib/database';
import { resolveAgentRuntimeOptions } from './agentRuntimeConfig';

/** What the generated project is shaped to run as. */
export type AgentCodegenTarget =
    /** `npm start "question"` — one shot, prints the answer. */
    | 'cli'
    /** Fastify HTTP service: POST /chat, GET /health, A2A agent card. */
    | 'server'
    /** Long-running queue consumer skeleton (BullMQ-shaped, broker left to the team). */
    | 'worker'
    /** AWS Lambda handler. */
    | 'lambda';

export interface AgentCodegenOptions {
    target: AgentCodegenTarget;
    /** npm package name. Defaults to the agent key. */
    packageName?: string;
    /** Baked into `.env.example` as the default console URL. */
    consoleBaseUrl?: string;
    /** Emit a Dockerfile + .dockerignore. Default: true for `server`/`worker`. */
    includeDockerfile?: boolean;
    /** Emit a `Makefile`-free minimal project (no README). Default: false. */
    omitReadme?: boolean;
}

export interface GeneratedFile {
    path: string;
    contents: string;
    /** Rendered in the download dialog's file tree. */
    description?: string;
}

export interface AgentCodegenResult {
    /** Slugged root folder name inside the archive. */
    rootDir: string;
    files: GeneratedFile[];
    /** Non-fatal things the operator should know before running the project. */
    warnings: string[];
}

