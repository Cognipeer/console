function writeTools(bindings: IAgentToolBinding[], agentName: string): GeneratedFile {
    const toolBindings = bindings.filter((b) => b.source === 'tool');
    const mcpBindings = bindings.filter((b) => b.source === 'mcp');
    const systemBindings = bindings.filter((b) => b.source === 'system');

    const body: string[] = [
        banner(agentName),
        '',
        "import { createTool } from '@cognipeer/agent-sdk';",
        "import { z } from 'zod';",
        '',
        "import { console_ } from './console.js';",
        '',
        '/**',
        ' * Tool surface, resolved from the console at startup.',
        ' *',
        ' * Schemas are fetched rather than inlined on purpose: an OpenAPI action or',
        ' * an MCP server that gains a parameter stays correct here without a',
        ' * regenerate. The trade-off is one round trip per source at boot.',
        ' */',
        'export async function buildTools() {',
        '  const tools = [];',
        '',
    ];

    for (const binding of toolBindings) {
        const allow = binding.toolNames?.length ? binding.toolNames : null;
        body.push(
            `  // Console tool source: ${binding.sourceKey}`,
            '  {',
            `    const definition = await console_.tools.get(${quote(binding.sourceKey)});`,
            `    const allowed = ${allow ? literal(allow, 0) : 'null'};`,
            '    for (const action of definition.actions ?? []) {',
            '      if (allowed && !allowed.includes(action.name)) continue;',
            '      tools.push(createTool({',
            '        name: action.name,',
            '        description: action.description || action.name,',
            '        // The console validates the real schema on execute; a permissive',
            '        // passthrough here avoids a second, drifting copy of it.',
            '        schema: z.object({}).passthrough(),',
            '        execute: async (args: Record<string, unknown>) =>',
            `          console_.tools.execute(${quote(binding.sourceKey)}, action.key, args),`,
            '      }));',
            '    }',
            '  }',
            '',
        );
    }

    for (const binding of mcpBindings) {
        const allow = binding.toolNames?.length ? binding.toolNames : null;
        body.push(
            `  // MCP server: ${binding.sourceKey}`,
            '  {',
            `    const server = console_.mcp.server(${quote(binding.sourceKey)});`,
            '    const descriptors = await server.listTools();',
            `    const allowed = ${allow ? literal(allow, 0) : 'null'};`,
            '    for (const descriptor of descriptors) {',
            '      if (allowed && !allowed.includes(descriptor.name)) continue;',
            '      tools.push(createTool({',
            '        name: descriptor.name,',
            '        description: descriptor.description || descriptor.name,',
            '        schema: z.object({}).passthrough(),',
            '        execute: async (args: Record<string, unknown>) =>',
            '          server.callTool(descriptor.name, args),',
            '      }));',
            '    }',
            '  }',
            '',
        );
    }

    if (systemBindings.length > 0) {
        body.push(
            '  // Built-in console tools are part of the console runtime and have no',
            '  // standalone equivalent. Re-bind them by calling the console agent, or',
            '  // replace them with your own implementation:',
            ...systemBindings.map((b) => `  //   - ${b.sourceKey} (${b.toolNames.join(', ') || 'all actions'})`),
            '',
        );
    }

    body.push('  return tools;', '}', '');
    return { path: 'src/tools.ts', description: 'Tools and MCP servers via console-sdk', contents: body.join('\n') };
}

