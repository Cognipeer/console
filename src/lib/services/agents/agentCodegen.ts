function writeModel(config: IAgentConfig, agentName: string): GeneratedFile {
    const modelSettings: Record<string, unknown> = {};
    if (config.temperature !== undefined) modelSettings.temperature = config.temperature;
    if (config.topP !== undefined) modelSettings.topP = config.topP;
    if (config.maxTokens !== undefined) modelSettings.maxTokens = config.maxTokens;

    return {
        path: 'src/model.ts',
        description: 'Model, routed through the console gateway',
        contents: `${banner(agentName)}

import { ChatOpenAI } from '@langchain/openai';
import { fromLangchainModel } from '@cognipeer/agent-sdk';

import { env } from './env.js';

/**
 * The model talks to the console's OpenAI-compatible gateway, not to the
 * provider. Keep it that way: it is what makes this agent's spend, guardrails
 * and traces show up in the console alongside the agent it was exported from.
 *
 * \`${config.modelKey ?? '<unset>'}\` is a console model KEY, not a provider
 * model id — the gateway resolves it to whichever deployment the project is
 * currently pointed at.
 */
export function createModel() {
  const lcModel = new ChatOpenAI({
    model: ${quote(config.modelKey ?? '')},
    apiKey: env.CONSOLE_API_KEY,
    configuration: { baseURL: \`\${env.CONSOLE_BASE_URL}/api/client/v1\` },
${Object.entries(modelSettings)
    .map(([key, value]) => `    ${key}: ${literal(value)},`)
    .join('\n')}
  });

  return fromLangchainModel(lcModel);
}
`,
    };
}

