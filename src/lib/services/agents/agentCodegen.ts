function writePackageJson(
    name: string,
    options: AgentCodegenOptions,
    needsConsoleSdk: boolean,
): GeneratedFile {
    const deps: Record<string, string> = {
        '@cognipeer/agent-sdk': SDK_VERSIONS.agentSdk,
        '@langchain/openai': SDK_VERSIONS.langchainOpenAI,
        dotenv: SDK_VERSIONS.dotenv,
        zod: SDK_VERSIONS.zod,
    };
    if (needsConsoleSdk) deps['@cognipeer/console-sdk'] = SDK_VERSIONS.consoleSdk;
    if (options.target === 'server') deps.fastify = SDK_VERSIONS.fastify;

    const entry = { cli: 'src/index.ts', server: 'src/server.ts', worker: 'src/worker.ts', lambda: 'src/lambda.ts' }[
        options.target
    ];

    const scripts: Record<string, string> = {
        dev: `tsx watch ${entry}`,
        build: 'tsc -p tsconfig.json',
        start: options.target === 'lambda' ? 'echo "deploy the built handler to Lambda"' : `node dist/${entry.replace('src/', '').replace('.ts', '.js')}`,
        typecheck: 'tsc --noEmit -p tsconfig.json',
    };

    return {
        path: 'package.json',
        description: 'Dependencies and scripts',
        contents: `${literal({
            name,
            version: '0.1.0',
            private: true,
            type: 'module',
            main: `dist/${entry.replace('src/', '').replace('.ts', '.js')}`,
            scripts,
            dependencies: Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b))),
            devDependencies: {
                '@types/node': SDK_VERSIONS.typesNode,
                tsx: SDK_VERSIONS.tsx,
                typescript: SDK_VERSIONS.typescript,
            },
            engines: { node: '>=20' },
        })}\n`,
    };
}

