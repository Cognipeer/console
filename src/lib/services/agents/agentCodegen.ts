// ── Helpers ──────────────────────────────────────────────────────────────

function slug(input: string): string {
    return (
        input
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, '-')
            .replace(/^-|-$/g, '') || 'agent'
    );
}

/** `JSON.stringify` with the indentation the generated files use. */
function literal(value: unknown, indent = 2): string {
    return JSON.stringify(value, null, indent) ?? 'undefined';
}

function quote(value: string): string {
    return JSON.stringify(value);
}

function banner(agentName: string): string {
    return [
        '// Generated by Cognipeer Console — Agent code export.',
        `// Source agent: ${agentName}`,
        '//',
        '// Edit freely: nothing re-imports this project. To keep the console copy',
        '// in sync, export/import the YAML manifest instead.',
    ].join('\n');
}

